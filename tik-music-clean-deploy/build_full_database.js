/**
 * build_full_database.js - Gộp và chuẩn hóa dữ liệu từ feed_data.json sang catalog_bundle.js
 */

const fs = require('fs');
const path = require('path');
const { runCollector } = require('./collect_catalog');

async function buildFullDatabase() {
  console.log('📦 Đang đồng bộ và xây dựng cơ sở dữ liệu đầy đủ...');
  await runCollector();
  const feedPath = path.join(__dirname, 'feed_data.json');
  const bundlePath = path.join(__dirname, 'catalog_bundle.js');
  if (fs.existsSync(feedPath)) {
    const data = JSON.parse(fs.readFileSync(feedPath, 'utf8'));
    fs.writeFileSync(
      bundlePath,
      `// Auto-generated by build_full_database.js\nwindow.INITIAL_CATALOG_DATA = ${JSON.stringify(data, null, 2)};\n`,
      'utf8'
    );
    console.log(`✅ Đã đóng gói ${data.tracks?.length || 0} bài nhạc vào catalog_bundle.js`);
  }
}

if (require.main === module) {
  buildFullDatabase();
}
